// Usage: node scripts/build-wada.mjs <colors.json> <out.ts>
// Treats the input as untrusted data: JSON.parse only, strict hex check on every colour.
import { readFileSync, writeFileSync } from "node:fs";

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) { console.error("usage: build-wada.mjs <colors.json> <out.ts>"); process.exit(1); }
const data = JSON.parse(readFileSync(inPath, "utf8"));
if (!Array.isArray(data)) throw new Error("colors.json is not an array");
const byN = new Map();
for (const c of data) {
  if (typeof c?.hex !== "string" || !/^#[0-9a-fA-F]{6}$/.test(c.hex)) throw new Error("bad hex: " + String(c?.hex));
  if (!Array.isArray(c.combinations)) throw new Error("bad combinations");
  for (const n of c.combinations) {
    if (!Number.isInteger(n) || n < 1 || n > 348) throw new Error("bad combination number: " + n);
    if (!byN.has(n)) byN.set(n, []);
    byN.get(n).push(c.hex.toLowerCase());
  }
}
const SOURCE = "after Sanzo Wada, A Dictionary of Color Combinations (1933–34); data mattdesl/dictionary-of-colour-combinations (MIT)";
const rows = [];
for (let n = 1; n <= 348; n++) {
  const colors = byN.get(n);
  if (!colors) throw new Error("missing palette " + n);
  rows.push(`  { id: "wada-${n}", name: "Wada No. ${n}", source: SOURCE, licence: "MIT", colors: ${JSON.stringify(colors)} },`);
}
const out = `// GENERATED by scripts/build-wada.mjs from vendor/wada/colors.json. Do not edit.
import type { CataloguePalette } from "./types";

const SOURCE = ${JSON.stringify(SOURCE)};

export const wadaPalettes: CataloguePalette[] = [
${rows.join("\n").replaceAll(JSON.stringify(SOURCE), "SOURCE")}
];
`;
writeFileSync(outPath, out);
console.log("wrote", rows.length, "palettes");
