// Generates src/studio/fonts.generated.ts from the installed @fontsource packages (latin subset, weights 400 and 600 only).
// Usage: node scripts/build-fonts.mjs   (run from the package root after npm install)
import fs from "node:fs";

const LIST = {
  sans: ["Inter", "Manrope", "DM Sans", "Plus Jakarta Sans", "IBM Plex Sans", "Work Sans", "Outfit", "Figtree", "Nunito Sans", "Rubik", "Space Grotesk", "Sora", "Urbanist", "Lexend", "Public Sans", "Source Sans 3"],
  serif: ["Source Serif 4", "Fraunces", "Lora", "Merriweather", "Playfair Display", "Libre Baskerville", "EB Garamond", "Crimson Pro", "Cormorant Garamond", "Newsreader", "Spectral", "DM Serif Display", "Instrument Serif"],
  display: ["Bricolage Grotesque", "Syne", "Unbounded", "Archivo Black", "Bebas Neue", "Righteous", "Abril Fatface", "Anton", "Climate Crisis"],
  mono: ["JetBrains Mono", "IBM Plex Mono", "Fira Code", "Space Mono", "Source Code Pro", "Roboto Mono"],
  handwriting: ["Caveat", "Kalam", "Patrick Hand", "Shadows Into Light"],
};

const rows = [];
const loaders = [];
for (const [category, names] of Object.entries(LIST)) {
  for (const family of names) {
    const slug = family.toLowerCase().replace(/ /g, "-");
    const dir = `node_modules/@fontsource/${slug}`;
    const pkg = JSON.parse(fs.readFileSync(`${dir}/package.json`, "utf8"));
    if (!["OFL-1.1", "Apache-2.0"].includes(pkg.license)) throw new Error(`${family}: licence ${pkg.license}`);
    const weights = [400, 600].filter((w) => fs.existsSync(`${dir}/latin-${w}.css`));
    if (!weights.length) throw new Error(`${family}: no latin 400/600`);
    rows.push(`  { family: ${JSON.stringify(family)}, category: "${category}", license: "${pkg.license}", weights: ${JSON.stringify(weights)} },`);
    const imports = weights.map((w) => `import("@fontsource/${slug}/latin-${w}.css")`).join(", ");
    loaders.push(`  ${JSON.stringify(family)}: () => Promise.all([${imports}]),`);
  }
}
const out = `// GENERATED by scripts/build-fonts.mjs from the installed @fontsource packages. Do not edit.
export type FontCategory = "sans" | "serif" | "display" | "mono" | "handwriting";
export interface CatalogueFont {
  family: string;
  category: FontCategory;
  license: "OFL-1.1" | "Apache-2.0";
  weights: number[];
}

export const FONT_CATALOGUE: CatalogueFont[] = [
${rows.join("\n")}
];

// Static import strings so the bundler splits each font into its own lazy chunk.
export const FONT_LOADERS: Record<string, () => Promise<unknown>> = {
${loaders.join("\n")}
};
`;
fs.writeFileSync("src/studio/fonts.generated.ts", out);
// The family NAMES only, for style-runtime (infers a font's `source`); style-studio's fonts.ts reads this list, so there is one list.
const names = Object.values(LIST).flat();
fs.writeFileSync(
  "../style-runtime/src/fontNames.ts",
  `// GENERATED by units/style-studio/scripts/build-fonts.mjs. Do not edit. Family names of the fonts the Style Studio bundles.
export const BUNDLED_FONT_NAMES: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
];

const BY_NAME = new Set(BUNDLED_FONT_NAMES.map((n) => n.toLowerCase()));
/** Whether a family name (case and edge-space insensitive) is one of the bundled fonts. */
export const isBundledFont = (name: string): boolean => BY_NAME.has(name.trim().toLowerCase());
`,
);
console.log(rows.length, "fonts");
