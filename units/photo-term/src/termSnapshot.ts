// A COLD-START SEED — a dated reading of the master, not a hand-kept list.
//
// ── WHY A SEED EXISTS AT ALL, AND WHY IT IS NOT THE THING WE JUST REMOVED ────────────────
//
// Two rules pull in opposite directions here, and both are right:
//
//   • Spellings must be derived from the type, never from a list an app keeps. A kept list
//     drifts the moment the master gains a spelling, and it drifts silently.
//   • A value the holder was given must RENDER. A field is never dropped because the surface
//     could not classify its term. "I could not reach the definition" is a claim about this
//     request; "there is no photo" is a claim about the data. An app that shows no face because
//     its network was cold has turned a timeout into apparent data loss.
//
// Resolve-only satisfies the first and breaks the second: on a fresh device with a cold or
// blocked master, the reader would search no keys and every face would go blank.
//
// So the seed is what it is honestly: a RECORDED MEASUREMENT of the master, with the date it
// was taken and the control that was run, regenerated by `npm run refresh-term` rather than
// edited by hand — and SUPERSEDED by the live read the moment one succeeds. It can never
// become the operative truth, because every successful resolve overwrites it in the cache.
//
// ⛔ Do not hand-edit the binding below. Run the refresh script; it reads the master.
// ⛔ Do not add a spelling here that the master does not serve. That is the defect returning.

